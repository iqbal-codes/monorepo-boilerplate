import { randomUUID } from "node:crypto";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { extname, join, resolve } from "node:path";

/**
 * Storage seam for uploads. The web app only ever receives a URL, so replacing
 * local disk with S3/Cloudflare R2 means implementing this interface and
 * changing one line in `apps/server/src/services.ts`.
 */
export type StoredFile = {
  key: string;
  url: string;
  size: number;
  contentType: string;
};

export type PutFileInput = {
  filename: string;
  contentType: string;
  data: ArrayBuffer;
};

export interface StorageAdapter {
  put(input: PutFileInput): Promise<StoredFile>;
  remove(key: string): Promise<void>;
}

const ALLOWED_CONTENT_TYPES: Record<string, true> = {
  "image/png": true,
  "image/jpeg": true,
  "image/webp": true,
  "image/gif": true,
  "image/svg+xml": true,
  "application/pdf": true,
};

export const MAX_UPLOAD_BYTES = 5 * 1024 * 1024;

export function isAllowedContentType(contentType: string): boolean {
  return ALLOWED_CONTENT_TYPES[contentType] === true;
}

export type LocalStorageOptions = {
  /** Directory on disk that holds uploaded files. */
  directory: string;
  /** Public base URL the server mounts that directory at. */
  publicPath?: string;
};

/**
 * Local-disk adapter used by the template: no external service, works offline,
 * served by Hono's `serveStatic`. Keys are content-addressed by UUID plus the
 * original extension so a URL is never guessable from a filename.
 */
export function createLocalStorage({
  directory,
  publicPath = "/uploads",
}: LocalStorageOptions): StorageAdapter {
  const root = resolve(directory);

  return {
    async put({ filename, contentType, data }) {
      if (!isAllowedContentType(contentType)) {
        throw new Error(`Unsupported content type: ${contentType}`);
      }
      if (data.byteLength > MAX_UPLOAD_BYTES) {
        throw new Error("File exceeds the 5 MB limit");
      }

      const extension = extname(filename).toLowerCase().slice(0, 10);
      const key = `${randomUUID()}${extension}`;
      await mkdir(root, { recursive: true });
      await writeFile(join(root, key), new Uint8Array(data));

      return {
        key,
        url: `${publicPath}/${key}`,
        size: data.byteLength,
        contentType,
      };
    },

    async remove(key) {
      // `key` is generated by `put`, but still refuse path traversal defensively.
      if (key.includes("/") || key.includes("\\") || key.includes("..")) {
        throw new Error("Invalid storage key");
      }
      await rm(join(root, key), { force: true });
    },
  };
}

/** Reads a stored file back; used by the static serving route in the server app. */
export async function readStoredFile(directory: string, key: string): Promise<Uint8Array> {
  if (key.includes("/") || key.includes("\\") || key.includes("..")) {
    throw new Error("Invalid storage key");
  }
  return readFile(join(resolve(directory), key));
}
